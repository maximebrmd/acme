"""Brings an environment's Cloudflare values from its Pulumi stack into the
inventory, so they live in one place, Pulumi's (packages/peal-infra/pulumi):

    uv run python scripts/cloudflare_from_pulumi.py \\
      --vault-id sandbox@scripts/vault-keychain-client.py

or production@…. It writes group_vars/<group>/cloudflare.yml, which is
committed and never edited by hand: the audience tags of the environment's
Access applications, its buckets and their endpoints. Then, once the stack has made them, it
writes the tunnel's token and the buckets' keys into the group's vault, as
Ansible encrypts it, and names the entries it changed, never their values.
Run it after each `pulumi up` of the environment, then site.yml.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

import yaml
from ansible.parsing.dataloader import DataLoader
from ansible.parsing.vault import VaultLib, VaultSecret, get_file_vault_secret

INFRA = Path(__file__).resolve().parent.parent
PULUMI = INFRA.parent / "pulumi" / "scripts" / "pulumi.ts"

HEADER = """---
# Generated by scripts/cloudflare_from_pulumi.py from the Pulumi stack
# environment/{group} (packages/peal-infra/pulumi): change the stack, never
# this file.
"""

# The Access application each audience tag of the inventory names, by
# environment: the sandbox has one application for its app, site and docs;
# production, public, one for its admin paths (peal_access_paths) alone.
AUD_NAMES = {
    "sandbox": {"sandbox": "app", "grafana": "grafana", "ssh": "ssh"},
    "production": {"admin": "admin", "grafana": "grafana", "ssh": "ssh"},
}

Outputs = dict[str, Any]


def stack_outputs(group: str) -> Outputs:
    """The environment stack's outputs, its secrets in clear: they go no
    further than the vault, encrypted."""
    ran = subprocess.run(
        ["bun", str(PULUMI), "environment", "stack", "output", "--json", "--show-secrets", "--stack", group],
        check=True,
        capture_output=True,
        text=True,
        stdin=subprocess.DEVNULL,
    )
    return json.loads(ran.stdout)


def inventory_values(group: str, outputs: Outputs) -> dict[str, Any]:
    """What the inventory takes from the stack, without a secret."""
    if group not in AUD_NAMES:
        raise SystemExit(f"No Pulumi stack describes {group} yet")
    endpoint = outputs["r2Endpoint"]
    return {
        "cloudflare_access_aud": {name: outputs["accessAud"][key] for name, key in AUD_NAMES[group].items()},
        "peal_media_endpoint": endpoint,
        "peal_media_bucket": outputs["mediaBucket"],
        "peal_backup_endpoint": endpoint.removeprefix("https://"),
        "peal_backup_bucket": outputs["backupBucket"],
    }


def vault_values(outputs: Outputs) -> dict[str, str] | None:
    """The secrets the vault takes from the stack, or None before the stack
    has made the buckets' keys."""
    if "mediaKey" not in outputs or "backupKey" not in outputs:
        return None
    return {
        "PEAL_S3_ACCESS_KEY_ID": outputs["mediaKey"]["accessKeyId"],
        "PEAL_S3_SECRET_ACCESS_KEY": outputs["mediaKey"]["secretAccessKey"],
        "PGBACKREST_REPO1_S3_KEY": outputs["backupKey"]["accessKeyId"],
        "PGBACKREST_REPO1_S3_KEY_SECRET": outputs["backupKey"]["secretAccessKey"],
    }


def write_private(path: Path, data: bytes) -> None:
    """Replaces a file at once, readable by its owner alone."""
    handle, name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        os.fchmod(handle, 0o600)
        os.write(handle, data)
    finally:
        os.close(handle)
    os.replace(name, path)


def update_vault(path: Path, password: bytes, tunnel_token: str, credentials: dict[str, str]) -> list[str]:
    """Writes the values into the vault, encrypted again with its password.
    Returns the names whose value changed."""
    secret = VaultSecret(password)
    vault = VaultLib([("default", secret)])
    data = yaml.safe_load(vault.decrypt(path.read_bytes())) or {}
    peal_credentials = data.setdefault("peal_credentials", {})
    changed = []
    if data.get("cloudflared_tunnel_token") != tunnel_token:
        data["cloudflared_tunnel_token"] = tunnel_token
        changed.append("cloudflared_tunnel_token")
    for name, value in credentials.items():
        if peal_credentials.get(name) != value:
            peal_credentials[name] = value
            changed.append(f"peal_credentials.{name}")
    if changed:
        text = yaml.safe_dump(data, sort_keys=False, allow_unicode=True)
        write_private(path, vault.encrypt(("---\n" + text).encode(), secret))
    return changed


def vault_password(group: str, source: str) -> bytes:
    secret = get_file_vault_secret(filename=source, vault_id=group, loader=DataLoader())
    secret.load()
    return secret.bytes


def main(argv: list[str] | None = None, outputs_of: Callable[[str], Outputs] = stack_outputs) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    # As Ansible takes it: the group, then its password's file or client
    # script (a name ending in -client, called with --vault-id <group>).
    parser.add_argument("--vault-id", required=True, metavar="GROUP@SOURCE")
    parser.add_argument("--inventory", type=Path, default=INFRA / "inventory")
    options = parser.parse_args(argv)
    group, at, source = options.vault_id.partition("@")
    if not (group and at and source):
        parser.error("--vault-id takes <group>@<password file or client script>")

    outputs = outputs_of(group)
    folder = options.inventory / "group_vars" / group
    values = yaml.safe_dump(inventory_values(group, outputs), sort_keys=False)
    (folder / "cloudflare.yml").write_text(HEADER.format(group=group) + values)
    print(f"Wrote group_vars/{group}/cloudflare.yml")

    credentials = vault_values(outputs)
    if credentials is None:
        print("The stack has no bucket keys yet: the vault is left as it is")
        return 0
    password = vault_password(group, source)
    changed = update_vault(folder / "vault.yml", password, outputs["tunnelToken"], credentials)
    print("Vault: " + (", ".join(changed) if changed else "nothing changed"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
