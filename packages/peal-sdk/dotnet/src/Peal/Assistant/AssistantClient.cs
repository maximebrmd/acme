    /// </summary>
    /// <example><code>
    /// await client.Assistant.SuggestAsync(
    ///     new SuggestionRequest
    ///     {
    ///         WorkspaceId = "workspaceId",
    ///         Action = new AssistantAction(
    ///             new AssistantAction.Rewrite(
    ///                 new AssistantActionRewrite { Tone = AssistantTone.Professional }
    ///             )
    ///         ),
    ///         Text = "text",
